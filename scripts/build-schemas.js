// Writes the published JSON Schema files from the zod schemas the MCP server
// enforces. Run with --check to fail when the committed files are stale.
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { dirname } from 'node:path';
import * as z from 'zod/v4';
import { PUBLISHED_SCHEMAS } from '../packages/mcp/src/schemas.js';
import { capabilities } from '../packages/cli/src/capabilities.js';
import { ruleCatalog, explain, ISSUE_CODES } from '../packages/core/src/index.js';

const RAW = 'https://raw.githubusercontent.com/aiscihub/cookieguard-ai/main';
const check = process.argv.includes('--check');
const outputs = {};
for (const [name, schema] of Object.entries(PUBLISHED_SCHEMAS)) {
  outputs[`schemas/${name}`] = JSON.stringify({ $id: `${RAW}/schemas/${name}`, ...z.toJSONSchema(schema, { target: 'draft-2020-12', io: 'output' }) }, null, 2) + '\n';
}
const document = JSON.stringify(capabilities(), null, 2) + '\n';
outputs['cookieguard.capabilities.json'] = document;
outputs['skills/cookieguard-browser-auth-security/references/capabilities.json'] = document;
outputs['skills/cookieguard-browser-auth-security/references/security-checks.md'] = [
  '# CookieGuard security checks', '',
  '<!-- Generated by scripts/build-schemas.js from the engine catalog. Do not edit. -->', '',
  'A `confirmed` finding needs a configured authentication cookie and observed attributes; it can fail a run.',
  'A `review` finding is heuristic or uncertain and never fails a run.', '',
  ...ruleCatalog().flatMap(rule => [`## ${rule.ruleId} ${rule.title} (${rule.severity})`, '',
    `- Checks: ${rule.checks}`, `- Confirmed when: ${rule.confirmedWhen}`, `- Review when: ${rule.reviewWhen}`,
    `- Why: ${rule.why}`, `- Fix: ${rule.fix}`, '']),
  '## Incomplete reasons', '',
  ...ISSUE_CODES.map(id => { const entry = explain(id); return `- \`${id}\`: ${entry.meaning} ${entry.fix}`; }), '',
  'Secure example: `' + explain('CG001').secureExample + '`', '',
].join('\n');

const stale = [];
for (const [path, contents] of Object.entries(outputs)) {
  if (check) {
    const current = await readFile(path, 'utf8').catch(() => null);
    if (current !== contents) stale.push(path);
  } else {
    await mkdir(dirname(path), { recursive: true });
    await writeFile(path, contents);
  }
}
if (stale.length) {
  process.stderr.write(`Stale generated files: ${stale.join(', ')}. Run npm run build:schemas.\n`);
  process.exitCode = 1;
} else process.stdout.write(check ? 'Generated schemas and capability documents are current.\n' : `Wrote ${Object.keys(outputs).length} generated files.\n`);
